import esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';

async function buildSnippet() {
  const distDir = path.resolve(process.cwd(), 'dist');
  const snippetDistDir = path.resolve(distDir, 'snippet');

  if (!fs.existsSync(distDir)) fs.mkdirSync(distDir, { recursive: true });
  if (!fs.existsSync(snippetDistDir)) fs.mkdirSync(snippetDistDir, { recursive: true });

  // 1. Build IIFE minified bundle for browser <script> tag
  const iifeResult = await esbuild.build({
    entryPoints: ['src/snippet/vf.ts'],
    outfile: path.join(distDir, 'vf.js'),
    bundle: true,
    minify: true,
    format: 'iife',
    globalName: 'vfGlobal',
    target: ['es2020'],
    write: true,
  });

  // Also copy to dist/snippet/vf.js for npm export
  await esbuild.build({
    entryPoints: ['src/snippet/vf.ts'],
    outfile: path.join(snippetDistDir, 'vf.js'),
    bundle: true,
    minify: false,
    format: 'esm',
    target: ['es2020'],
    write: true,
  });

  // Read minified content and write it into a TypeScript constant for Worker serving
  const minifiedContent = fs.readFileSync(path.join(distDir, 'vf.js'), 'utf-8');
  const embeddedTs = `// Auto-generated by scripts/build-snippet.js - DO NOT EDIT MANUALLY\nexport const EMBEDDED_SNIPPET_JS = ${JSON.stringify(minifiedContent)};\n`;
  fs.writeFileSync(path.resolve(process.cwd(), 'src/snippet/embedded.ts'), embeddedTs, 'utf-8');

  console.log(`✓ Snippet bundled successfully (${minifiedContent.length} bytes minified)`);
}

buildSnippet().catch((err) => {
  console.error('Failed to build snippet:', err);
  process.exit(1);
});
